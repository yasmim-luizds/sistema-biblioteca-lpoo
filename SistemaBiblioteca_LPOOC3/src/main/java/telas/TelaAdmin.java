    private void btnCadastrarAlunoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarAlunoActionPerformed
        String nome = JOptionPane.showInputDialog(this, "Nome do aluno:");
        if (nome == null || nome.isBlank()) {
            return;
        }

        String email = JOptionPane.showInputDialog(this, "Email:");
        if (email == null) {
            return;
        }

        String login = JOptionPane.showInputDialog(this, "Login:");
        if (login == null) {
            return;
        }

        String senha = JOptionPane.showInputDialog(this, "Senha:");
        if (senha == null) {
            return;
        }

        String matriculaStr = JOptionPane.showInputDialog(this, "Matrícula:");
        if (matriculaStr == null) {
            return;
        }

        String curso = JOptionPane.showInputDialog(this, "Curso:");
        if (curso == null) {
            return;
        }

        String periodoStr = JOptionPane.showInputDialog(this, "Período:");
        if (periodoStr == null) {
            return;
        }

        try {
            int matricula = Integer.parseInt(matriculaStr);
            int periodo = Integer.parseInt(periodoStr);

            Aluno aluno = new Aluno(nome, email, login, senha, matricula, curso, periodo);
            sistema.adicionarUsuario(aluno);
            JOptionPane.showMessageDialog(this, "Aluno cadastrado com sucesso!");
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Matrícula ou período inválidos.");
        }
    }//GEN-LAST:event_btnCadastrarAlunoActionPerformed

