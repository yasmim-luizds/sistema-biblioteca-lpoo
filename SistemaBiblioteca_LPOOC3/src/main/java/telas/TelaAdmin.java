    private void btnAprovarEmprestActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAprovarEmprestActionPerformed
        java.util.List<Emprestimo> pendentes = new java.util.ArrayList<>();
        for (Emprestimo e : sistema.listarEmprestimos()) {
            if ("PENDENTE".equals(e.getStatus())) {
                pendentes.add(e);
            }
        }
        if (pendentes.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Não há empréstimos pendentes.");
            return;
        }

        String[] opcoes = new String[pendentes.size()];
        for (int i = 0; i < pendentes.size(); i++) {
            opcoes[i] = (i + 1) + " - " + pendentes.get(i).toString();
        }

        String escolha = (String) JOptionPane.showInputDialog(
                this,
                "Selecione um empréstimo para aprovar:",
                "Aprovar Empréstimo",
                JOptionPane.PLAIN_MESSAGE,
                null,
                opcoes,
                opcoes[0]
        );

        if (escolha == null) {
            return;
        }

        int indice = Integer.parseInt(escolha.split(" ")[0]) - 1;
        Emprestimo selecionado = pendentes.get(indice);

        try {
            sistema.aprovarEmprestimo(selecionado);
            JOptionPane.showMessageDialog(this, "Empréstimo aprovado com sucesso!");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao aprovar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAprovarEmprestActionPerformed

